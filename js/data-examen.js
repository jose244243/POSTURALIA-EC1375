/* Baraja sin mutar (Fisher–Yates) */
export function barajar(arreglo) {
  const a = [...arreglo];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/* Devuelve `n` índices del banco, barajados o en orden */
export function seleccionarReactivos(n, mezclar = true) {
  const indices = BANCO.map((_, i) => i);
  const base = mezclar ? barajar(indices) : indices;
  return base.slice(0, Math.min(n, BANCO.length));
}
